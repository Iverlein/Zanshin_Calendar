"""Writing to the knowledge pool in its layers (docs/sources/STRUCTURE.md): the mechanical
side of recording a reading. kb.py reads the pool; this script writes it. Every command
validates against the registry (sources.yaml) and the index, writes nothing on an error, and
can be run again. The judgement — which passage, which state is honest, what is one claim,
whether a doubt is a question — is the `sources` skill's (.claude/skills/sources/SKILL.md),
which drives this script.

  pool.py stub SIGLUM CHAPTER [--title T]       the corpus file of a chapter, with its frontmatter,
                                                 and its row in README's generated index
  pool.py passage ID --title T --state S [--date D] [--tibetan FILE] [--english FILE] [--file F]
                                                 a passage into its corpus file, in page order
                                                 (FILE "-" reads stdin; --json FILE takes all of it)
  pool.py claim SLUG --title T --type K --cites IDS [--terms X] [--feeds X] [--open QS] --body FILE
  pool.py question --title T --cites IDS [--waits X] [--body FILE]
                                                 numbered on from the last question anywhere
  pool.py answer QID --date D --body FILE [--cites IDS]
  pool.py anchor FILE [--write]                  the first migration step for a legacy topic file:
                                                 its passage headings get their ids and anchors
  pool.py split FILE [--write]                   the second: its passage sections move into the
                                                 corpus files of their chapters, a pointer left behind
  pool.py index                                  README's generated index of the layered files
  pool.py next-question                          the next free question number

Passage ids: `<siglum>[.<volume>]:<locator>`, `wb.2:p331`, `wb.1:p351-379`, `kp:box12` (kb.py).
"""
import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import kb  # noqa: E402

INDEX_START = "<!-- pool index: generated by tools/sources/pool.py index, do not edit -->"
INDEX_END = "<!-- end pool index -->"
STATES = kb.STATES


def fail(msg):
    sys.exit(f"pool.py: {msg}")


def read_text(arg):
    if arg is None:
        return ""
    if arg == "-":
        return sys.stdin.read()
    return Path(arg).read_text()


def load_index(root):
    ix = kb.Index(root)
    ix.read_all()
    return ix


def split_list(s):
    return [x.strip() for x in re.split(r"[,\s]+", s or "") if x.strip()]


def front_and_body(text):
    m = kb.FRONT.match(text)
    if not m:
        return {}, text, ""
    return kb.yaml.safe_load(m.group(1)) or {}, text[m.end():], m.group(0)


def dump_front(d):
    return "---\n" + kb.yaml.safe_dump(d, allow_unicode=True, sort_keys=False, default_flow_style=None).rstrip("\n") + "\n---\n"


def chapter_of(ix, sig, vol, page):
    v = (ix.sources[sig].get("volumes") or {}).get(vol) or {}
    chs = sorted((v.get("chapters") or {}).items(), key=lambda kv: kv[1])
    found = None
    for ch, start in chs:
        if page >= start:
            found = ch
    return found


def chapter_span(ix, sig, ch):
    for vol, v in (ix.sources[sig].get("volumes") or {}).items():
        chs = sorted((v.get("chapters") or {}).items(), key=lambda kv: kv[1])
        for i, (c, start) in enumerate(chs):
            if c == ch:
                end = chs[i + 1][1] - 1 if i + 1 < len(chs) else (v.get("pages") or [0, start])[1]
                return vol, start, end
    return None, None, None


def corpus_path(ix, sig, ch):
    d = ix.sources_dir / "corpus" / sig
    if ch is None:
        return d / f"{sig}.md"
    existing = sorted(d.glob(f"ch{ch:02d}*.md")) if d.exists() else []
    return existing[0] if existing else d / f"ch{ch:02d}.md"


# --- stub ---------------------------------------------------------------------------------

def cmd_stub(args):
    ix = load_index(args.root)
    sig = args.siglum.lower()
    if sig not in ix.sources:
        fail(f"{sig} is not in sources.yaml")
    ch = int(args.chapter) if args.chapter else None
    vol, lo, hi = chapter_span(ix, sig, ch) if ch else (None, None, None)
    if ch and vol is None:
        fail(f"{sig} has no chapter {ch} in sources.yaml")
    path = corpus_path(ix, sig, ch)
    if path.exists():
        print(f"exists: {path.relative_to(ix.root)}")
        return
    title = args.title or (f"{sig.upper()} ch. {ch}" if ch else sig.upper())
    front = {"kind": "corpus", "source": sig}
    if vol:
        front["volume"] = vol
    if ch:
        front["chapter"] = ch
        front["pages"] = f"{lo}–{hi}"
    front["read"] = "machine"
    up = "../" * (len(path.relative_to(ix.sources_dir).parts) - 1)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_front(front) + f"# {title}\n\nSigla, numbering and quoting rules are in [README.md]({up}README.md);\nthe shape of this file, [STRUCTURE.md]({up}STRUCTURE.md). Passages in the\ntext's order, each under its id, with its `*Read:*` line.\n")
    print(f"made {path.relative_to(ix.root)}")
    write_index(ix.root)


# --- passage ------------------------------------------------------------------------------

def cmd_passage(args):
    ix = load_index(args.root)
    data = json.loads(read_text(args.json)) if args.json else {}
    pid = kb.norm_dash(data.get("id") or args.id or "")
    p = kb.parse_pid(pid)
    if not p:
        fail(f"not a passage id: {pid}")
    sig = p["siglum"]
    if sig not in ix.sources:
        fail(f"unknown siglum {sig}")
    src = ix.sources[sig]
    if "volumes" in src and p["vol"] is None and p["loc"].startswith("p"):
        fail(f"{sig} has volumes: give one, {sig}.<vol>:{p['loc']}")
    if p["vol"] is not None and p["vol"] not in (src.get("volumes") or {}):
        fail(f"{sig} has no volume {p['vol']}")
    title = data.get("title") or args.title
    state = (data.get("state") or args.state or "").lower()
    if not title or state not in STATES:
        fail("a passage needs --title and --state scan|machine|etext")
    date = data.get("date") or args.date
    tib = data.get("tibetan") or read_text(args.tibetan)
    eng = data.get("english") or read_text(args.english)
    if state == "scan" and not kb.re.search(r"[ༀ-࿿]", tib or ""):
        fail("a passage read on the scan is written out in Tibetan: give --tibetan")
    if args.file:
        path = ix.root / args.file
    else:
        ch = chapter_of(ix, sig, p["vol"], p["lo"]) if p["loc"].startswith("p") else None
        path = corpus_path(ix, sig, ch)
        if not path.exists():
            fail(f"{path.relative_to(ix.root)} does not exist: `pool.py stub {sig} {ch or ''}` first")
    text = path.read_text()
    front, body, raw = front_and_body(text)
    if front.get("kind") != "corpus":
        fail(f"{path.relative_to(ix.root)} is not a corpus file (kind: corpus)")
    if front.get("source", "").lower() != sig or (front.get("volume") and p["vol"] and int(front["volume"]) != p["vol"]):
        fail(f"{path.relative_to(ix.root)} holds {front.get('source')} vol. {front.get('volume')}, not {pid}")
    anchor = kb.anchor_of(pid)
    if f'id="{anchor}"' in body:
        fail(f"{pid} is already in {path.relative_to(ix.root)}")
    level = "##"
    section = f"{level} <a id=\"{anchor}\"></a>{pid} {title}\n\n*Read: {state}" + (f", {date}" if date else "") + ".*\n"
    if tib.strip():
        section += "\n> " + tib.strip().replace("\n", "\n> ") + "\n"
    if eng.strip():
        section += "\n" + eng.strip() + "\n"
    # in page order: before the first passage heading whose lo is greater
    lines = body.splitlines(keepends=True)
    insert_at = len(lines)
    for i, line in enumerate(lines):
        h = kb.HEADING.match(line)
        if not h:
            continue
        first = kb.ANCHOR.sub("", h.group(2)).split()
        q = kb.parse_pid(kb.norm_dash(first[0])) if first else None
        if q and (q["lo"], q["hi"]) > (p["lo"], p["hi"]):
            insert_at = i
            break
    new_body = "".join(lines[:insert_at]).rstrip("\n") + "\n\n" + section + ("\n" + "".join(lines[insert_at:]) if insert_at < len(lines) else "")
    path.write_text(raw + new_body)
    print(f"{pid} into {path.relative_to(ix.root)}#{anchor} [{state}]")


# --- claim ---------------------------------------------------------------------------------

def check_cites(ix, cites):
    known = {}
    for key, (pid, p, state, rel, h, n, a) in ix.passages.items():
        known.setdefault((p["siglum"], p["vol"]), []).append((p["lo"], p["hi"], state, rel))
    out = []
    for c in cites:
        p = kb.parse_pid(kb.norm_dash(c))
        if not p:
            fail(f"not a passage id: {c}")
        if p["siglum"] not in ix.sources:
            fail(f"unknown siglum in {c}")
        hits = [x for x in known.get((p["siglum"], p["vol"]), []) if kb.overlaps(x[0], x[1], p["lo"], p["hi"])]
        if not hits:
            print(f"warning: {c} is quoted nowhere in the pool yet", file=sys.stderr)
        elif all(x[2] == "etext" for x in hits):
            print(f"warning: {c} rests on the etext only", file=sys.stderr)
        out.append(kb.norm_dash(c))
    return out


def cmd_claim(args):
    ix = load_index(args.root)
    slug = re.sub(r"[^a-z0-9-]", "-", args.slug.lower()).strip("-")
    path = ix.sources_dir / "claims" / f"{slug}.md"
    if path.exists():
        fail(f"{path.relative_to(ix.root)} exists")
    if args.type not in ("definition", "list", "table", "rule", "remedy", "conflict", "note"):
        fail("--type is definition | list | table | rule | remedy | conflict | note")
    cites = check_cites(ix, split_list(args.cites))
    if not cites:
        fail("a claim cites at least one passage")
    body = read_text(args.body).strip()
    if not body:
        fail("a claim has a body (--body FILE or -)")
    front = {"kind": "claim", "type": args.type, "terms": split_list(args.terms), "cites": cites,
             "feeds": split_list(args.feeds), "open": split_list(args.open)}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_front(front) + f"# {args.title}\n\n{body}\n")
    print(f"made {path.relative_to(ix.root)}")
    write_index(ix.root)


# --- questions -----------------------------------------------------------------------------

def next_question(ix):
    last = max([q[0] for q in ix.rows["question"]] or [0])
    return last + 1


def cmd_next_question(args):
    print(next_question(load_index(args.root)))


def cmd_question(args):
    ix = load_index(args.root)
    n = next_question(ix)
    cites = check_cites(ix, split_list(args.cites))
    path = ix.sources_dir / "questions" / f"q{n:04d}.md"
    front = {"kind": "question", "id": f"q{n}", "state": "open", "asked": args.date or dt.date.today().isoformat(),
             "answered": None, "cites": cites, "waits": split_list(args.waits)}
    body = read_text(args.body).strip()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_front(front) + f"# {args.title}\n" + (f"\n{body}\n" if body else ""))
    print(f"q{n}: {path.relative_to(ix.root)}")
    write_index(ix.root)


def cmd_answer(args):
    ix = load_index(args.root)
    n = int(args.qid.lstrip("q"))
    path = ix.sources_dir / "questions" / f"q{n:04d}.md"
    if not path.exists():
        fail(f"q{n} is not a question file; a question of open-questions.md is answered by hand, in its item")
    front, body, raw = front_and_body(path.read_text())
    if front.get("state") == "answered":
        fail(f"q{n} is answered already")
    cites = check_cites(ix, split_list(args.cites)) if args.cites else []
    front["state"] = "answered"
    front["answered"] = args.date
    front["cites"] = list(dict.fromkeys((front.get("cites") or []) + cites))
    answer = read_text(args.body).strip()
    if not answer:
        fail("an answer has a body")
    path.write_text(dump_front(front) + body.rstrip("\n") + f"\n\n## Answered {args.date}\n\n{answer}\n")
    print(f"q{n} answered")
    write_index(ix.root)


# --- migration -----------------------------------------------------------------------------

def legacy_passages(ix, rel):
    """The passages kb.py inferred for a legacy file: line -> (pid, anchor, heading)."""
    return {n: (pid, a, h) for key, (pid, p, state, r, h, n, a) in ix.passages.items() if r == rel}


def cmd_anchor(args):
    ix = load_index(args.root)
    path = (ix.root / args.file) if not args.file.startswith("docs/") else ix.root / args.file
    if not path.exists():
        path = ix.sources_dir / args.file
    rel = path.relative_to(ix.root).as_posix()
    found = legacy_passages(ix, rel)
    lines = path.read_text().splitlines(keepends=True)
    changed = 0
    taken = set(re.findall(r'<a id="([^"]+)"></a>', "".join(lines)))
    for n, (pid, anchor, heading) in sorted(found.items()):
        line = lines[n - 1]
        h = kb.HEADING.match(line)
        if not h or f'id="{anchor}"' in line:
            continue
        first = kb.ANCHOR.sub("", h.group(2)).split()
        if first and kb.parse_pid(kb.norm_dash(first[0])):
            continue
        base = pid
        for letter in "bcdefgh":                    # the same pages quoted twice: the second gets a letter
            if kb.anchor_of(pid) not in taken:
                break
            pid = base + letter
        anchor = kb.anchor_of(pid)
        taken.add(anchor)
        lines[n - 1] = f'{h.group(1)} <a id="{anchor}"></a>{pid} {kb.ANCHOR.sub("", h.group(2))}\n'
        changed += 1
        print(f"{rel}:{n}: {pid}")
    unresolved = [(n, h) for n, h in ((n, l) for n, l in enumerate(lines, 1) if kb.HEADING.match(l))
                  if n not in found and kb.CITE.search(h) and (kb.CITE.search(h).group("p1") or kb.CITE.search(h).group("i1"))]
    for n, h in unresolved:
        print(f"{rel}:{n}: not resolved, anchor by hand: {h.strip()[:80]}")
    if args.write and changed:
        path.write_text("".join(lines))
    print(f"{changed} headings anchored{'' if args.write else ' (dry run: --write to apply)'}, {len(unresolved)} not resolved")


def cmd_split(args):
    ix = load_index(args.root)
    path = ix.root / args.file if (ix.root / args.file).exists() else ix.sources_dir / args.file
    rel = path.relative_to(ix.root).as_posix()
    text = path.read_text()
    front, body, raw = front_and_body(text)
    lines = body.splitlines(keepends=True)
    heads = [(n, kb.HEADING.match(l)) for n, l in enumerate(lines, 1) if kb.HEADING.match(l)]
    moves = []                                      # (start line, end line, pid, p, title)
    for i, (n, h) in enumerate(heads):
        first = kb.ANCHOR.sub("", h.group(2)).split()
        p = kb.parse_pid(kb.norm_dash(first[0])) if first else None
        if not p:
            continue
        level = len(h.group(1))
        end = len(lines) + 1
        for m, h2 in heads[i + 1:]:
            if len(h2.group(1)) <= level:
                end = m
                break
        moves.append((n, end, kb.norm_dash(first[0]), p, " ".join(first[1:])))
    if not moves:
        fail(f"{rel} has no anchored passage headings: `pool.py anchor {rel} --write` first")
    targets = {}
    for n, end, pid, p, title in moves:
        if p["siglum"] not in ix.sources:
            fail(f"unknown siglum in {pid}")
        ch = chapter_of(ix, p["siglum"], p["vol"], p["lo"]) if p["loc"].startswith("p") else None
        targets.setdefault((p["siglum"], ch), []).append((n, end, pid, p, title))
    plan = []
    for (sig, ch), items in targets.items():
        target = corpus_path(ix, sig, ch)
        for n, end, pid, p, title in items:
            plan.append((n, end, pid, p, title, target))
            print(f"{rel}:{n}-{end - 1}: {pid} -> {target.relative_to(ix.root)}#{kb.anchor_of(pid)}")
    if not args.write:
        print(f"{len(plan)} sections would move (dry run: --write to apply)")
        return
    up = lambda t: Path(*[".."] * (len(t.relative_to(ix.sources_dir).parts) - 1)).as_posix()  # noqa: E731
    removed = set()
    for n, end, pid, p, title, target in sorted(plan, key=lambda x: (x[5], x[3]["lo"], x[3]["hi"])):
        if not target.exists():
            vol, lo, hi = chapter_span(ix, p["siglum"], chapter_of(ix, p["siglum"], p["vol"], p["lo"])) if p["loc"].startswith("p") else (p["vol"], None, None)
            cmd_stub(argparse.Namespace(root=args.root, siglum=p["siglum"], chapter=chapter_of(ix, p["siglum"], p["vol"], p["lo"]) if p["loc"].startswith("p") else None, title=None))
        section = "".join(lines[n - 1:end - 1])
        state = next((s for key, (q, pp, s, r, h, ln, a) in ix.passages.items() if r == rel and ln == n), None)
        section_lines = section.splitlines(keepends=True)
        head = section_lines[0]
        rest = "".join(section_lines[1:])
        if state and not re.search(r"^\*Read:", rest, re.M):
            rest = f"\n*Read: {state} (inferred from {Path(rel).name}; confirm).*\n" + rest
        head = re.sub(r"^#+", "##", head, count=1)
        depth = len(target.relative_to(ix.sources_dir).parts) - 1 - (len(Path(rel).relative_to("docs/sources").parts) - 1)
        if depth > 0:                               # relative links of the moved text, from the deeper file
            rest = re.sub(r"\]\((?!https?://|#|\.\./)([^)]+\.md(?:#[^)]*)?)\)", lambda m: "](" + "../" * depth + m.group(1) + ")", rest)
        rest = re.sub(r"^(#+)", lambda m: "#" * max(3, len(m.group(1)) + (2 - (len(section_lines[0]) - len(section_lines[0].lstrip('#'))))), rest, flags=re.M)
        t = target.read_text()
        tf, tb, traw = front_and_body(t)
        tlines = tb.splitlines(keepends=True)
        at = len(tlines)
        for i, l in enumerate(tlines):
            h = kb.HEADING.match(l)
            if h:
                f = kb.ANCHOR.sub("", h.group(2)).split()
                q = kb.parse_pid(kb.norm_dash(f[0])) if f else None
                if q and (q["lo"], q["hi"]) > (p["lo"], p["hi"]):
                    at = i
                    break
        tb = "".join(tlines[:at]).rstrip("\n") + "\n\n" + head + rest.rstrip("\n") + "\n" + ("\n" + "".join(tlines[at:]) if at < len(tlines) else "")
        target.write_text(traw + tb)
        for k in range(n - 1, end - 1):
            removed.add(k)
        link = f"{target.relative_to(ix.sources_dir).as_posix()}#{kb.anchor_of(pid)}"
        pointer = f"- *{title}*: moved to [{link}]({link}) ({pid}).\n"
        lines[n - 1] = pointer
        removed.discard(n - 1)
    path.write_text(raw + "".join(l for k, l in enumerate(lines) if k not in removed))
    print(f"{len(plan)} sections moved; the claims the file states in its own words stay here, to be cut into claims/ by the sources skill")
    write_index(ix.root)


# --- the generated index -------------------------------------------------------------------

def index_text(ix):
    rows = []
    for rel, kind, title, words, front in sorted(ix.rows["file"]):
        if kind not in ("corpus", "claim", "question"):
            continue
        fm = json.loads(front) if front else {}
        name = Path(rel).relative_to("docs/sources").as_posix()
        if kind == "corpus":
            n = sum(1 for key, (pid, p, s, r, h, ln, a) in ix.passages.items() if r == rel)
            states = {}
            for key, (pid, p, s, r, h, ln, a) in ix.passages.items():
                if r == rel:
                    states[s] = states.get(s, 0) + 1
            state = ", ".join(f"{states[s]} {s}" for s in STATES if s in states) or "nothing read yet"
            rows.append(f"| [{name}]({name}) | corpus | {title} | {n} passages: {state} |")
        elif kind == "claim":
            rows.append(f"| [{name}]({name}) | claim, {fm.get('type', '?')} | {title} | cites {', '.join(fm.get('cites') or [])}; feeds {', '.join(str(x) for x in fm.get('feeds') or []) or '—'} |")
        else:
            rows.append(f"| [{name}]({name}) | question {fm.get('id', '')} | {title} | {fm.get('state', 'open')}; cites {', '.join(fm.get('cites') or []) or '—'} |")
    if not rows:
        return None
    return "\n".join([INDEX_START, "", "| File | Kind | Title | State |", "| --- | --- | --- | --- |"] + rows + ["", INDEX_END])


def write_index(root):
    ix = load_index(root)
    readme = ix.sources_dir / "README.md"
    text = readme.read_text()
    block = index_text(ix)
    if block is None:
        return
    if INDEX_START in text:
        new = re.sub(re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END), lambda m: block, text, flags=re.S)
    else:
        m = re.search(r"^## How the files quote", text, re.M)
        head = "## The layers\n\nThe corpus, claim and question files of [STRUCTURE.md](STRUCTURE.md), listed by\n`tools/sources/pool.py index` from their frontmatter.\n\n"
        new = text[:m.start()] + head + block + "\n\n" + text[m.start():] if m else text.rstrip("\n") + "\n\n" + head + block + "\n"
    if new != text:
        readme.write_text(new)
        print("README.md: index regenerated")


def cmd_index(args):
    write_index(args.root)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".")
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("stub"); p.add_argument("siglum"); p.add_argument("chapter", nargs="?"); p.add_argument("--title"); p.set_defaults(fn=cmd_stub)
    p = sp.add_parser("passage"); p.add_argument("id", nargs="?"); p.add_argument("--title"); p.add_argument("--state"); p.add_argument("--date")
    p.add_argument("--tibetan"); p.add_argument("--english"); p.add_argument("--file"); p.add_argument("--json"); p.set_defaults(fn=cmd_passage)
    p = sp.add_parser("claim"); p.add_argument("slug"); p.add_argument("--title", required=True); p.add_argument("--type", required=True)
    p.add_argument("--cites", required=True); p.add_argument("--terms"); p.add_argument("--feeds"); p.add_argument("--open"); p.add_argument("--body", required=True); p.set_defaults(fn=cmd_claim)
    p = sp.add_parser("question"); p.add_argument("--title", required=True); p.add_argument("--cites"); p.add_argument("--waits"); p.add_argument("--body"); p.add_argument("--date"); p.set_defaults(fn=cmd_question)
    p = sp.add_parser("answer"); p.add_argument("qid"); p.add_argument("--date", required=True); p.add_argument("--body", required=True); p.add_argument("--cites"); p.set_defaults(fn=cmd_answer)
